"""Generate the Streamlit adapter from DESIGN.md's canonical tokens."""

import json
from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[1]
meta = yaml.safe_load((root / "DESIGN.md").read_text().split("---", 2)[1])
(root / "src/memebot/data/theme.json").write_text(json.dumps(meta, indent=2) + "\n")
c = meta["colors"]
(
    root / ".streamlit/config.toml"
).write_text(f'''# Generated by scripts/sync_theme.py; edit DESIGN.md instead.
[theme]
base = "light"
primaryColor = "{c["primary"]}"
backgroundColor = "{c["background"]}"
secondaryBackgroundColor = "{c["surface"]}"
textColor = "{c["ink"]}"
font = "sans serif"
[server]
address = "127.0.0.1"
headless = true
[browser]
gatherUsageStats = false
''')
